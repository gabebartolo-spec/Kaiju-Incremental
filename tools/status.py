"""Write docs/STATUS.md from live sources, so nobody edits it by hand (director 2026-10-21).

Sources: GitHub (open PRs, PRs merged in the last 3 days, via `gh`), each task's one state file
(~/.claude/handoffs/kaiju/*.md, outside git, its State line and branch), and the open director questions in docs/DESIGN.md.
Run from the repo root after merges:  python tools/status.py [--notes <session notes dir>] [--stdout]
"""

import datetime
import glob
import json
import os
import re
import subprocess
import sys

REPO = "gabebartolo-spec/Kaiju-Incremental"
BASE = "main"
DAYS = 2


def gh(args):
    out = subprocess.run(["gh"] + args + ["--repo", REPO], capture_output=True, text=True,
                         encoding="utf-8", check=True).stdout
    return json.loads(out or "[]")


def prs():
    fields = "number,title,headRefName,isDraft,updatedAt,statusCheckRollup"
    open_ = gh(["pr", "list", "--state", "open", "--json", fields, "--limit", "50"])
    since = (datetime.date.today() - datetime.timedelta(days=DAYS)).isoformat()
    merged = [p for p in gh(["pr", "list", "--state", "merged", "--base", BASE,
                             "--json", "number,title,mergedAt", "--limit", "60"])
              if (p.get("mergedAt") or "")[:10] >= since]
    return open_, merged


def checks(pr):
    states = [c.get("conclusion") or c.get("status") or "" for c in pr.get("statusCheckRollup") or []]
    if not states:
        return "no checks"
    if any(s in ("FAILURE", "CANCELLED", "TIMED_OUT") for s in states):
        return "red"
    if all(s in ("SUCCESS", "SKIPPED", "NEUTRAL") for s in states):
        return "green"
    return "running"


# One copy per role, outside git, shared by both Claude accounts (director 2026-10-25).
HANDOFFS = os.path.expanduser("~/.claude/handoffs/kaiju")


def tasks(notes):
    rows = []
    paths = sorted(glob.glob(os.path.join(HANDOFFS, "*.md")))
    if notes:  # tasks started before 2026-10-21 evening keep <notes>/<task>/handoff.md until they end
        paths += sorted(glob.glob(os.path.join(notes, "*", "handoff.md")))
    for path in paths:
        name = os.path.basename(path)[:-3]
        if name == "handoff":
            name = os.path.basename(os.path.dirname(path)) + " (notes)"
        if name == "README":
            continue
        with open(path, encoding="utf-8") as f:
            head = f.read(4000)
        # "State: x", "STATE: x" mid-line, "State (date): x", or a "## State ..." heading with the state on the next line
        state = (re.search(r"\bstate\b[^\n]{0,30}?:(?!\d)\s*(\S.*)$", head, re.M | re.I)
                 or re.search(r"^#+\s*state\b[^\n]*\n+\s*[-*]?\s*(\S.*)$", head, re.M | re.I))
        branch = re.search(r"(?:^|[\s`(])(claude/[a-z0-9][\w.-]*)(?![\w/-]*\.md)", head, re.M)
        if state and re.match(r"(?i)\W*done\b", state.group(1)):
            continue  # finished: the lead archives it
        rows.append((name, state.group(1).strip()[:110] if state else "-", branch.group(1) if branch else "-"))
    return rows


def questions():
    with open("docs/DESIGN.md", encoding="utf-8") as f:
        text = f.read()
    m = re.search(r"## Open for the director[^\n]*\n(.*?)(?:\n## |\Z)", text, re.S)
    return " ".join(m.group(1).split()) if m else "-"


def main():
    open_, merged = prs()
    now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    out = ["# Status board", "",
           "GENERATED by `python tools/status.py` (%s); never edit by hand. Plan: `docs/ROADMAP.md`;" % now,
           "design: `docs/DESIGN.md`; each task's state: its `~/.claude/handoffs/kaiju/<task>.md`.", "",
           "## Open PRs", "", "| PR | Branch | Checks | Title |", "|----|--------|--------|-------|"]
    out += ["| #%d%s | %s | %s | %s |" % (p["number"], " (draft)" if p["isDraft"] else "", p["headRefName"],
                                         checks(p), p["title"]) for p in open_] or ["| - | - | - | none |"]
    out += ["", "## Merged into %s, last %d days" % (BASE, DAYS), ""]
    out += [" · ".join("#%d %s" % (p["number"], p["title"]) for p in sorted(merged, key=lambda p: p["number"]))
            or "none"]
    out += ["", "## Tasks (one state file each)", "", "| Task | State | Branch |", "|------|-------|--------|"]
    notes = sys.argv[sys.argv.index("--notes") + 1] if "--notes" in sys.argv else ""
    out += ["| %s | %s | %s |" % r for r in tasks(notes)]
    out += ["", "## Open director questions (from DESIGN.md)", "", questions(), ""]
    text = "\n".join(out)
    if "--stdout" in sys.argv:
        sys.stdout.write(text)
    else:
        with open("docs/STATUS.md", "w", encoding="utf-8", newline="\n") as f:
            f.write(text)


if __name__ == "__main__":
    main()
