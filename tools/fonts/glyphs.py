# --- Accented capitals: base skeleton + a two-row mark one row clear above the cap height.
# Rows above the cap come first in the list; ABOVE says how many there are.
MARKS = {
    "acute": ["..##", "##.."],
    "grave": ["##..", "..##"],
    "circ": ["..##..", "##..##"],
    "diaer": ["##..##", "##..##"],
    "tilde": ["###..#", "#..###"],
    "breve": ["#....#", ".####."],
}
ABOVE: dict[str, int] = {}


def _accent(base: str, mark: str) -> list[str]:
    rows = GLYPHS[base]
    m = MARKS[mark]
    w = max(len(rows[0]), len(m[0]))
    return [r.center(w, ".") for r in m] + ["." * w] + [r.center(w, ".") for r in rows]


