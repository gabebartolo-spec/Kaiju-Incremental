"""Makes SliceLit.shader and SliceWater.shader (unity/Assets/Resources/Shaders) from the HDRP package's own Lit.shader.

HDRP's Lit keeps every lighting, shadow, fog and GI path; only its surface is swapped: each LitData.hlsl
include becomes SliceSurface.hlsl (the voxel colour rules) or SliceWater.hlsl (the water). Only the passes the slice draws stay,
and the texture features and lightmap variants go, so the shader compiles to few variants.

Run after a package update, with the editor having resolved packages once:
    python tools/unity/build_lit_shader.py
"""

from __future__ import annotations

import glob
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2] / "unity"
SHADERS = ROOT / "Assets/Resources/Shaders"
LIT_DATA = '#include "Packages/com.unity.render-pipelines.high-definition/Runtime/Material/Lit/LitData.hlsl"'
DROP_PRAGMAS = (
    "shader_feature",
    "DOTS_INSTANCING_ON",
    "LIGHTMAP_ON",
    "DIRLIGHTMAP_COMBINED",
    "DYNAMICLIGHTMAP_ON",
    "SHADOWS_SHADOWMASK",
    "DECALS_",
    "DECAL_SURFACE_GRADIENT",
    "PROBE_VOLUMES_",
    "LOD_FADE_CROSSFADE",
    "RENDERING_LAYERS",
    "USE_LEGACY_LIGHTMAPS",
)
HEADER = """// Generated by tools/unity/build_lit_shader.py from the HDRP package's Lit.shader. Do not edit by hand.
"""
SLICE_KINDS = """
    HLSLINCLUDE
    #pragma multi_compile_local SLICE_BUILDING SLICE_CUBE SLICE_FILL SLICE_DEBRIS SLICE_GROUND
    #pragma instancing_options procedural:SliceSetup
    #if defined(SLICE_BUILDING)
    #define _DOUBLESIDED_ON
    #endif
    ENDHLSL
"""
# Always transparent: the one keyword is always on (the material state is in WaterView.cs).
WATER_KINDS = """
    HLSLINCLUDE
    #pragma multi_compile_local _SURFACE_TYPE_TRANSPARENT
    #define _ENABLE_FOG_ON_TRANSPARENT
    ENDHLSL
"""


def pass_blocks(text: str) -> list[tuple[int, int, str]]:
    """Every top-level Pass in the subshader: start, end (past the closing brace), name."""
    blocks = []
    for found in re.finditer(r"^\s*Pass\s*\n\s*\{", text, flags=re.M):
        depth = 0
        at = text.index("{", found.start())
        end = at
        while True:
            if text[end] == "{":
                depth += 1
            elif text[end] == "}":
                depth -= 1
                if depth == 0:
                    break
            end += 1
        name = re.search(r'Name\s+"([^"]+)"', text[at:end]).group(1)
        blocks.append((found.start(), end + 1, name))
    return blocks


def emit(out: str, title: str, surface: str, keep: set[str], kinds: str) -> None:
    pattern = str(ROOT / "Library/PackageCache/com.unity.render-pipelines.high-definition@*")
    package = glob.glob(pattern)[0]
    source = Path(package, "Runtime/Material/Lit/Lit.shader").read_text(encoding="utf8")

    first = source.index("SubShader")
    second = source.index("SubShader", first + 10)  # the ray-tracing one
    tail = source.index("FallBack", second)
    text = source[:second] + source[tail:]

    for start, end, name in reversed(pass_blocks(text)):
        if name not in keep:
            text = text[:start] + text[end:]

    lines = []
    for line in text.split("\n"):
        stripped = line.strip()
        if stripped.startswith("#pragma") and any(key in stripped for key in DROP_PRAGMAS):
            continue
        if stripped.startswith("CustomEditor"):
            continue
        lines.append(line)
    text = "\n".join(lines)

    count = text.count(LIT_DATA)
    assert count == len(keep), f"expected one surface include a pass, found {count}"
    text = text.replace(LIT_DATA, f'#include "Assets/Resources/Shaders/{surface}"')
    text = text.replace('Shader "HDRP/Lit"', f'Shader "{title}"', 1)
    text = text.replace("    SubShader", kinds + "    SubShader", 1)
    (SHADERS / out).write_text(HEADER + text, encoding="utf8", newline="\n")
    print(f"{out}: {text.count(chr(10))} lines, {count} passes")


def main() -> None:
    emit("SliceLit.shader", "Slice/Lit", "SliceSurface.hlsl", {"GBuffer", "ShadowCaster", "DepthOnly", "Forward"}, SLICE_KINDS)
    emit("SliceWater.shader", "Slice/Water", "SliceWater.hlsl", {"Forward"}, WATER_KINDS)


if __name__ == "__main__":
    main()
